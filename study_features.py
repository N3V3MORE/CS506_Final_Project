"""CPU-only transcript features; no audio loading or speech inference.

Run: python study_features.py selection.csv --output new_features.jsonl
Uses CMUdict first pronunciations, with G2P only for single-phone proportions.
Within-word pairs and stress features use CMUdict-covered words only.
"""

import argparse
from collections import Counter
import csv
from functools import cache
import json
import os
from pathlib import Path
import re

from build_features import PHONEMES, VOWELS, WORD_PATTERN
from transcribe_selection import read_selection


def extract_study_features(reference_text, cmu, g2p, normalize_text):
    if not isinstance(reference_text, str) or not reference_text.strip():
        raise ValueError("reference_text must not be empty")
    words = WORD_PATTERN.findall(reference_text.lower())
    normalized = normalize_text(re.sub(r"(?<=[A-Za-z])-(?=[A-Za-z])", "", reference_text))
    if not words or not isinstance(normalized, str) or not normalized.split():
        raise ValueError("reference_text must contain raw and normalized words")

    phone_counts = Counter()
    bigram_counts = Counter()
    known_words = long_words = stressed_words = noninitial_words = 0
    g2p_words = []
    unresolved_words = []
    for word in words:
        if word in cmu:
            pronunciation = cmu[word][0]
            phones = [re.sub(r"\d", "", phone) for phone in pronunciation]
            if not phones or set(phones).difference(PHONEMES):
                raise ValueError(f"{word}: invalid CMUdict pronunciation")
            known_words += 1
            bigram_counts.update(f"{left}|{right}" for left, right in zip(phones, phones[1:]))
            vowels = [phone for phone in pronunciation if re.sub(r"\d", "", phone) in VOWELS]
            long_words += len(vowels) >= 3
            primary_positions = [index for index, phone in enumerate(vowels) if phone.endswith("1")]
            if len(vowels) >= 2 and primary_positions:
                stressed_words += 1
                noninitial_words += primary_positions[0] > 0
        else:
            phones = [re.sub(r"\d", "", phone) for phone in g2p(word)
                      if isinstance(phone, str) and re.sub(r"\d", "", phone) in PHONEMES]
            if phones:
                g2p_words.append(word)
            else:
                unresolved_words.append(word)
        phone_counts.update(phones)

    num_phonemes = sum(phone_counts.values())
    return {
        "words": words,
        "normalized_num_words": len(normalized.split()),
        "num_words": len(words),
        "cmudict_missing_proportion": (len(g2p_words) + len(unresolved_words)) / len(words),
        "mean_word_length": sum(map(len, words)) / len(words),
        "phoneme_proportions": [phone_counts[phone] / num_phonemes if num_phonemes else 0.0
                                for phone in PHONEMES],
        "bigram_counts": dict(sorted(bigram_counts.items())),
        "num_pairs": sum(bigram_counts.values()),
        "long_word_share": long_words / known_words if known_words else 0.0,
        "noninitial_stress_share": noninitial_words / stressed_words if stressed_words else 0.0,
        "num_phonemes": num_phonemes,
        "g2p_words": g2p_words,
        "unresolved_words": unresolved_words,
    }


def export_study_features(selection_file, output_file, cmu, g2p, normalize_text):
    output_file = Path(output_file)
    if output_file.exists():
        raise FileExistsError(f"Output already exists: {output_file}. Choose another --output.")
    rows = []
    for clip in read_selection(selection_file):
        row = {key: clip[key] for key in ("audio_id", "speaker_id", "chapter_id", "reference_text")}
        try:
            row.update(extract_study_features(clip["reference_text"], cmu, g2p, normalize_text))
        except ValueError as error:
            raise ValueError(f"{clip['audio_id']}: {error}") from error
        rows.append(row)

    output_file.parent.mkdir(parents=True, exist_ok=True)
    with output_file.open("x", encoding="utf-8", newline="") as destination:
        for row in rows:
            destination.write(json.dumps(row, ensure_ascii=False, allow_nan=False) + "\n")
    return len(rows)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("input", type=Path, help="selection CSV generated by select_clips.py")
    parser.add_argument("--output", type=Path, required=True, help="new JSONL feature file")
    parser.add_argument("--nltk-data", type=Path, help="existing local NLTK resource directory")
    args = parser.parse_args()
    try:
        if args.output.exists():
            raise FileExistsError(f"Output already exists: {args.output}. Choose another --output.")
        if args.nltk_data:
            if not args.nltk_data.is_dir():
                raise ValueError(f"NLTK directory does not exist: {args.nltk_data}")
            os.environ["NLTK_DATA"] = str(args.nltk_data.resolve())
        import cmudict
        import nltk
        from whisper.normalizers import EnglishTextNormalizer

        if args.nltk_data:
            nltk.data.path.insert(0, str(args.nltk_data.resolve()))
        # G2p checks the ZIP files at import; fail before it can download them.
        for resource in ("corpora/cmudict.zip", "taggers/averaged_perceptron_tagger.zip",
                         "taggers/averaged_perceptron_tagger_eng"):
            nltk.data.find(resource)
        from g2p_en import G2p

        count = export_study_features(args.input, args.output, cmudict.dict(),
                                      cache(G2p()), EnglishTextNormalizer())
    except (OSError, ValueError, KeyError, csv.Error, ImportError, LookupError) as error:
        parser.exit(1, f"Error: {error}\n")
    print(f"Saved transcript features for {count} clips to {args.output}")


if __name__ == "__main__":
    main()
