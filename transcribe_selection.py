r"""Transcribe a saved LibriSpeech selection with OpenAI Whisper base.en on CUDA.

Windows setup (Python 3.11):
    python -m venv .venv
    .\.venv\Scripts\python.exe -m pip install -r requirements-transcription.txt

Test one clip: python transcribe_selection.py --limit 1
Process the list: python transcribe_selection.py

Defaults to outputs/dev-other_selected_clips_1000.csv. Successful rows are
saved immediately; later runs skip them. --limit uses the first N list entries,
including saved entries. CUDA is required; inference never falls back to CPU.
"""

import argparse
import csv
from functools import cache
import io
import json
import math
from pathlib import Path
import re
from time import perf_counter
from urllib.error import HTTPError
from urllib.parse import urlencode
from urllib.request import urlopen

from select_clips import DATASET_OPTIONS


MODEL_NAME = "base.en"
DEVICE = "cuda:0"
RESULT_COLUMNS = ["audio_id", "speaker_id", "reference_text", "predicted_text", "wer"]


def read_selection(input_file):
    with Path(input_file).open(encoding="utf-8-sig", newline="") as source:
        reader = csv.DictReader(source, strict=True)
        if reader.fieldnames != ["dataset", "audio_id", "speaker_id", "chapter_id", "reference_text"]:
            raise ValueError("Expected a selection CSV generated by select_clips.py.")
        clips = list(reader)
    seen_ids = set()
    for clip in clips:
        if None in clip or any(value is None or not value.strip() for value in clip.values()):
            raise ValueError("Selection contains an incomplete row.")
        clip_id = clip["audio_id"]
        if not re.fullmatch(r"[0-9]+-[0-9]+-[0-9]+", clip_id):
            raise ValueError(f"Invalid LibriSpeech audio ID: {clip_id}")
        speaker, chapter, _ = clip_id.split("-")
        if speaker != clip["speaker_id"] or chapter != clip["chapter_id"]:
            raise ValueError(f"{clip_id}: speaker or chapter does not match the audio ID.")
        if clip["dataset"] not in DATASET_OPTIONS:
            raise ValueError(f"Unknown dataset: {clip['dataset']}")
        if clip_id in seen_ids:
            raise ValueError(f"Duplicate audio ID: {clip_id}")
        seen_ids.add(clip_id)
    if not clips or len({clip["dataset"] for clip in clips}) != 1:
        raise ValueError("Selection must contain clips from one LibriSpeech split.")
    return clips


def read_completed(output_file, clips):
    output_file = Path(output_file)
    if not output_file.exists() or output_file.stat().st_size == 0:
        return set()
    selection = {clip["audio_id"]: clip for clip in clips}
    completed = set()
    with output_file.open(encoding="utf-8-sig", newline="") as source:
        reader = csv.DictReader(source, strict=True)
        if reader.fieldnames != RESULT_COLUMNS:
            raise ValueError("Existing results have an incompatible CSV header. Choose another --output.")
        for row in reader:
            if None in row or any(value is None for value in row.values()):
                raise ValueError("Existing results contain an incomplete row.")
            clip_id = row["audio_id"]
            if clip_id not in selection or clip_id in completed:
                raise ValueError(f"{clip_id}: unexpected or duplicate ID in existing results.")
            if any(row[key] != selection[clip_id][key] for key in ("speaker_id", "reference_text")):
                raise ValueError(f"{clip_id}: existing results do not match this selection.")
            error_rate = float(row["wer"])
            if not math.isfinite(error_rate) or error_rate < 0:
                raise ValueError(f"{clip_id}: invalid saved WER.")
            completed.add(clip_id)
    return completed


def load_gpu_model():
    import torch

    if not torch.cuda.is_available():
        raise RuntimeError("CUDA is unavailable. Install requirements-transcription.txt; CPU inference is disabled.")
    import whisper

    print(f"Device: {DEVICE} | {torch.cuda.get_device_name(0)}", flush=True)
    print(f"PyTorch: {torch.__version__} | CUDA: {torch.version.cuda} | Model: {MODEL_NAME}", flush=True)
    model = whisper.load_model(
        MODEL_NAME, device=DEVICE,
        download_root=str(Path(__file__).resolve().parent / "outputs" / "models"),
    )
    if str(model.device) != DEVICE:
        raise RuntimeError(f"Expected {DEVICE}, but Whisper loaded on {model.device}.")
    print(f"Whisper loaded on {model.device}", flush=True)
    return model


@cache
def load_audio_metadata(dataset_name):
    """Read the split's audio links once instead of searching for each clip."""
    config, split = DATASET_OPTIONS[dataset_name]
    recordings = {}
    while True:
        query = urlencode({
            "dataset": "openslr/librispeech_asr", "config": config, "split": split,
            "offset": len(recordings), "length": 100,
        })
        with urlopen(f"https://datasets-server.huggingface.co/rows?{query}", timeout=30) as response:
            data = json.load(response)
        if data["partial"] or not data["rows"]:
            raise ValueError("Hugging Face returned incomplete audio metadata.")
        for item in data["rows"]:
            sample = item["row"]
            if sample["id"] in recordings:
                raise ValueError(f"Duplicate audio ID in dataset: {sample['id']}")
            recordings[sample["id"]] = sample
        if len(recordings) == data["num_rows_total"]:
            return recordings
        if len(recordings) > data["num_rows_total"]:
            raise ValueError("Hugging Face returned inconsistent clip counts.")


def fetch_audio(clip):
    try:
        recordings = load_audio_metadata(clip["dataset"])
    except (OSError, ValueError, KeyError) as error:
        raise RuntimeError(f"Could not load audio metadata: {error}. Saved results are kept.") from error
    sample = recordings[clip["audio_id"]]
    if (sample["id"] != clip["audio_id"] or str(sample["speaker_id"]) != clip["speaker_id"]
            or str(sample["chapter_id"]) != clip["chapter_id"] or sample["text"] != clip["reference_text"]):
        raise ValueError("Dataset metadata does not match the saved selection.")
    audio_source = sample["audio"][0]
    if audio_source["type"] not in ("audio/flac", "audio/x-flac"):
        raise ValueError("Expected FLAC audio from the dataset.")
    with urlopen(audio_source["src"], timeout=60) as response:
        audio_bytes = response.read()
    import soundfile as sf

    try:
        audio, sample_rate = sf.read(io.BytesIO(audio_bytes), dtype="float32")
    except sf.LibsndfileError as error:
        raise ValueError(f"Could not decode audio: {error}") from error
    if audio.ndim == 2:
        audio = audio.mean(axis=1)
    if sample_rate != 16000 or audio.ndim != 1 or len(audio) == 0:
        raise ValueError("Expected nonempty 16 kHz mono audio.")
    return audio


def score_transcription(reference, prediction):
    from jiwer import wer
    from whisper.normalizers import EnglishTextNormalizer

    normalizer = EnglishTextNormalizer()
    # Match run_baseline.py, including joining internal hyphens.
    reference = normalizer(re.sub(r"(?<=[A-Za-z])-(?=[A-Za-z])", "", reference))
    prediction = normalizer(re.sub(r"(?<=[A-Za-z])-(?=[A-Za-z])", "", prediction))
    return wer(reference, prediction)


def run_selection(input_file, output_file, limit=None):
    if limit is not None and limit < 1:
        raise ValueError("--limit must be positive.")
    clips = read_selection(input_file)
    completed = read_completed(output_file, clips)
    if limit is not None:
        clips = clips[:limit]
    pending = [clip for clip in clips if clip["audio_id"] not in completed]
    print(f"Requested: {len(clips)} | Already saved: {len(clips) - len(pending)} | To transcribe: {len(pending)}")
    if not pending:
        return 0, 0

    model = load_gpu_model()
    output_file = Path(output_file)
    output_file.parent.mkdir(parents=True, exist_ok=True)
    needs_header = not output_file.exists() or output_file.stat().st_size == 0
    saved = failed = 0
    with output_file.open("a", encoding="utf-8", newline="") as destination:
        writer = csv.DictWriter(destination, fieldnames=RESULT_COLUMNS)
        if needs_header:
            writer.writeheader()
            destination.flush()
        for index, clip in enumerate(pending, start=1):
            try:
                audio = fetch_audio(clip)
                started = perf_counter()
                prediction = model.transcribe(audio, language="en", fp16=False)["text"]
                error_rate = score_transcription(clip["reference_text"], prediction)
                seconds = perf_counter() - started
            except (OSError, ValueError, KeyError) as error:
                if isinstance(error, HTTPError) and error.code == 429:
                    raise RuntimeError("Dataset server rate limit reached. Try again later; saved clips are kept.") from error
                print(f"Failed {clip['audio_id']}: {error}", flush=True)
                failed += 1
                continue
            writer.writerow({
                "audio_id": clip["audio_id"], "speaker_id": clip["speaker_id"],
                "reference_text": clip["reference_text"], "predicted_text": prediction,
                "wer": error_rate,
            })
            destination.flush()
            saved += 1
            print(f"Clip {index}/{len(pending)} | {clip['audio_id']} | WER: {error_rate:.2%} | {seconds:.2f}s",
                  flush=True)
            if len(pending) == 1:
                print(f"Reference:  {clip['reference_text']}")
                print(f"Prediction: {prediction}")
    print(f"Saved: {saved} | Failed: {failed} | Results: {output_file}")
    return saved, failed


def main():
    project_dir = Path(__file__).resolve().parent
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("input", nargs="?", type=Path,
                        default=project_dir / "outputs" / "dev-other_selected_clips_1000.csv")
    parser.add_argument("--limit", type=int, help="use only the first N selection entries")
    parser.add_argument("--output", type=Path, help="results CSV; matching saved rows are resumed")
    args = parser.parse_args()
    output_file = args.output or project_dir / "outputs" / f"{args.input.stem}_results_{MODEL_NAME}.csv"
    try:
        _, failed = run_selection(args.input, output_file, args.limit)
    except (OSError, ValueError, KeyError, csv.Error, RuntimeError, ImportError) as error:
        parser.exit(1, f"Error: {error}\n")
    if failed:
        parser.exit(1, f"{failed} clip(s) failed and remain eligible for retry.\n")


if __name__ == "__main__":
    main()
